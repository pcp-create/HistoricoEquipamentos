import {test,expect} from '@playwright/test';
test('CRM quotes list filters, opens child sections and links to existing editor',async({page,context})=>{
 await context.addCookies([{name:'m8-access',value:'test',domain:'localhost',path:'/'}]);
 await page.route('**/api/activity',r=>r.fulfill({json:{admin:false}}));
 const row={company_id:2,id:'7',number:'P-7',revision:1,client:'Cliente',description:'Manutenção',emission:'2026-10-21',validity:'2026-10-28',total:'20',status:'EmAndamento',situation:'Em digitação',type_name:'Preventiva',products:1,detail_at:'2026-10-21',pending:false};
 await page.route('**/api/m8-quotes?**',r=>{const p=new URL(r.request().url()).searchParams;
 if(p.has('overview'))return r.fulfill({json:{quotes:1,clients:1,detailed:1,updated:'2026-10-21T15:00:00Z',statuses:['EmAndamento'],types:['Preventiva'],situations:['Em digitação']}});
 if(p.has('id'))return r.fulfill({json:{payload:{observacoes:'Observação original',valorFrete:0,aprovado:false},products:[{id:1,produtoNome:'Filtro',quantidade:1,valorUnitario:20,valorTotal:20}],services:[{id:1,servicoNome:'Revisão',quantidade:1}],sellers:[{id:1,vendedorNome:'Ana',percentual:100}],detail_at:'2026-10-21',pending:false}});
 return r.fulfill({json:{rows:p.get('company')==='1'?[]:[p.get('view')==='materials'?{...row,item_id:'1',material:'Filtro especial',product_id:'50',quantity:'2',unit:'UN',unit_price:'10',material_total:'20'}:row],total:p.get('company')==='1'?0:1,page:1,size:50}});
 });
 await page.goto('/orcamentos');
 await expect(page.getByRole('heading',{name:'Orçamentos',exact:true})).toBeVisible();
 await expect(page.getByRole('link',{name:'Novo Orçamento'})).toHaveAttribute('href','/orcamentos/novo');
 await page.getByRole('button',{name:'Ver orçamento P-7'}).click();
 const dialog=page.getByRole('dialog');await expect(dialog.getByRole('cell',{name:'Filtro',exact:true})).toBeVisible();
 const box=await dialog.boundingBox();expect(box!.x).toBeGreaterThan(0);expect(Math.abs(box!.x+box!.width-1440)).toBeLessThanOrEqual(2);
 await dialog.getByText('Todos os campos do orçamento',{exact:true}).click();
 await expect(dialog.locator('dt[title="valorFrete"] + dd')).toHaveText('0');
 await expect(dialog.locator('dt[title="aprovado"] + dd')).toHaveText('Não');
 await dialog.getByText('Todos os campos · Produto 1',{exact:true}).click();
 await expect(dialog.locator('dt[title="produtoNome"] + dd')).toHaveText('Filtro');
 await page.setViewportSize({width:390,height:844});
 await expect.poll(()=>dialog.evaluate(el=>el.getBoundingClientRect().width)).toBeLessThanOrEqual(390);
 await page.setViewportSize({width:1440,height:1080});
 await dialog.getByRole('button',{name:'Vendedores (1)'}).click();await expect(dialog.getByRole('cell',{name:'Ana'})).toBeVisible();
 await dialog.getByRole('button',{name:'Serviços (1)'}).click();await expect(dialog.getByRole('cell',{name:'Revisão',exact:true})).toBeVisible();
 await dialog.getByRole('button',{name:'Fechar detalhes'}).click();
 await page.getByRole('button',{name:'Por material',exact:true}).click();
 await expect(page.getByRole('button',{name:'Por material',exact:true})).toHaveAttribute('aria-pressed','true');
 await expect(page.getByRole('columnheader',{name:'Material / referência'})).toBeVisible();
 await expect(page.getByText('Filtro especial',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Por orçamento',exact:true}).click();
 await expect(page.getByRole('columnheader',{name:'Material / referência'})).toHaveCount(0);
 await page.getByRole('button',{name:'Filtros de pesquisa'}).click();await page.getByRole('combobox',{name:/Empresa/}).selectOption('1');
 await page.getByRole('button',{name:'Aplicar filtros'}).click();await expect(page.getByText('Nenhum orçamento encontrado para os filtros informados.')).toBeVisible();
});
