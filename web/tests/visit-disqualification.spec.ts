import {test,expect} from '@playwright/test';
test.use({viewport:{width:390,height:844},hasTouch:true});
test('swipe disqualifies with a reason and moves the customer through the scrollable menu',async({page,context})=>{
 await context.addCookies([{name:'m8-refresh',value:'test',domain:'localhost',path:'/'}]);
 const customer:any={key:'m8:1',name:'Cliente teste',document:'123',city:'Lages',uf:'SC',address:'',lead:false,latitude:null,longitude:null,lastVisit:null,health:'overdue'};
 const writes:any[]=[];
 await page.route('**/api/visits',async r=>{if(r.request().method()==='POST'){const b=r.request().postDataJSON();writes.push(b);if(b.action==='restore_customer')delete customer.disqualification;else customer.disqualification={reason:b.reason,actor:'a@test',created_at:new Date().toISOString()};await r.fulfill({json:{saved:true}})}else await r.fulfill({json:{name:'Vendedor',customers:[customer],visits:[]}})});
 await page.goto('/visitas');
 await page.getByRole('button',{name:/Visitas Sua carteira/}).click();
 await page.getByRole('button',{name:'Lista',exact:true}).click();
 const card=page.locator('.visit-swipe-content');
 await card.dispatchEvent('touchstart',{touches:[{identifier:0,clientX:300,clientY:300}]});
 await card.dispatchEvent('touchend',{changedTouches:[{identifier:0,clientX:180,clientY:290}]});
 await expect(page.locator('.visit-swipe')).toHaveClass(/revealed/);
 await page.getByRole('button',{name:'Desqualificar Cliente',exact:true}).click();
 const dialog=page.getByRole('dialog',{name:'Desqualificar cliente ou Lead'});
 await expect(dialog.getByRole('button',{name:'Confirmar desqualificação'})).toBeDisabled();
 await dialog.getByLabel('Justificativa').fill('Fora do perfil de atendimento');
 await dialog.getByRole('button',{name:'Confirmar desqualificação'}).click();
 await expect(dialog).toHaveCount(0);
 await expect(page.locator('.sales-customer-grid .sales-customer')).toHaveCount(0);
 await page.getByRole('button',{name:'Ver mais abas',exact:true}).click();
 await expect.poll(()=>page.locator('.sales-list-tabs').evaluate(el=>el.scrollLeft)).toBeGreaterThan(0);
 await expect(page.locator('.sales-list-next')).toBeHidden();
 await page.getByRole('button',{name:'Desqualificado (1)',exact:true}).click();
 await expect(page.locator('.sales-customer-grid')).toContainText('Fora do perfil de atendimento');
 expect(writes).toEqual([{action:'disqualify',customer_key:'m8:1',reason:'Fora do perfil de atendimento'}]);
 expect(await page.locator('.sales-list-tabs').evaluate(el=>{const boxes=[...el.children].map(c=>c.getBoundingClientRect());return boxes.every(b=>b.top===boxes[0].top)&&getComputedStyle(el).scrollbarWidth==='none'})).toBe(true);
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.locator('.sales-list-tabs').evaluate(el=>el.scrollTo({left:0}));
 await expect(page.getByRole('button',{name:'Ver mais abas'})).toBeVisible();
 await page.getByRole('button',{name:'Resumo',exact:true}).click();
 const summary=page.getByRole('button',{name:/Desqualificados.*Ver desqualificados/});
 await expect(summary.locator('strong')).toHaveText('1');
 await summary.click();
 await expect(page.locator('.sales-customer-grid')).toContainText('Fora do perfil de atendimento');
 await card.dispatchEvent('touchstart',{touches:[{identifier:0,clientX:300,clientY:300}]});
 await card.dispatchEvent('touchend',{changedTouches:[{identifier:0,clientX:180,clientY:290}]});
 await page.getByRole('button',{name:'Restaurar Cliente',exact:true}).click();
 await expect(page.locator('.sales-customer-grid .sales-customer')).toHaveCount(0);
 await page.getByRole('button',{name:'Clientes (1)',exact:true}).click();
 await expect(page.locator('.sales-customer-grid')).toContainText('Cliente teste');
 expect(writes.at(-1)).toEqual({action:'restore_customer',customer_key:'m8:1'});
 await page.setViewportSize({width:1440,height:900});
 await expect(page.locator('.sales-list-next')).toBeHidden();
});
