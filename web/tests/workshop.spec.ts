 await expect.poll(()=>writes.length).toBe(1);
 expect(writes[0]).toMatchObject({action:'stage',id:machine.id,version:1,stage:'repair'});
 await expect(page.getByRole('dialog',{name:'Ficha da máquina'})).toHaveCount(0);
