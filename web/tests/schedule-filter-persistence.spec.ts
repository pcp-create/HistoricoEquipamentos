import {test,expect} from '@playwright/test';
test('programming restores user filters and calendar navigation after leaving and reloading',async({page,context})=>{
 await context.addCookies([{name:'m8-access',value:'test',domain:'localhost',path:'/'}]);
 await page.route('**/api/activity',r=>r.fulfill({json:{admin:true}}));
 let email='planner@test.com';
 await page.route('**/api/service-scheduling',r=>r.fulfill({json:{email,schedules:[],users:[{email:'ana',display_name:'Ana'},{email:'bia',display_name:'Bia'}],settings:{document:{vehicles:[]}}}}));
 await page.goto('/programacao');
 await page.getByRole('textbox',{name:'Pesquisar OS, cliente, equipamento ou cidade'}).fill('Compressor teste');
 await page.getByRole('button',{name:'Executante',exact:true}).click();
 const panel=page.getByRole('dialog',{name:'Filtrar Executante',exact:true});
 await panel.getByRole('checkbox',{name:'Selecionar todos',exact:true}).uncheck();
 await panel.getByRole('checkbox',{name:'Ana',exact:true}).check();
 await page.keyboard.press('Escape');
 await page.getByLabel('Visão por data',{exact:true}).selectOption('operation');
 await page.getByLabel('Mês da operação programada').selectOption('10');
 await page.getByRole('button',{name:'Calendário',exact:true}).click();
 await page.getByRole('button',{name:'Dia',exact:true}).click();
 await page.getByRole('button',{name:'Próximo dia',exact:true}).click();
 const heading=(await page.locator('.schedule-orders-calendar h2').textContent())!;
 await page.goto('/login');
 await page.goto('/programacao');
 await expect(page.getByRole('textbox',{name:'Pesquisar OS, cliente, equipamento ou cidade'})).toHaveValue('Compressor teste');
 await expect(page.getByRole('button',{name:'Executante',exact:true})).toContainText('Ana');
 await expect(page.getByLabel('Visão por data',{exact:true})).toHaveValue('operation');
 await expect(page.getByLabel('Mês da operação programada')).toHaveValue('10');
 await expect(page.getByRole('button',{name:'Dia',exact:true})).toHaveAttribute('aria-pressed','true');
 await expect(page.locator('.schedule-orders-calendar h2')).toHaveText(heading);
 await page.reload();
 await expect(page.locator('.schedule-orders-calendar h2')).toHaveText(heading);
 email='another@test.com';
 await page.reload();
 await expect(page.getByRole('textbox',{name:'Pesquisar OS, cliente, equipamento ou cidade'})).toHaveValue('');
 await expect(page.getByRole('button',{name:'Executante',exact:true})).toContainText('Todos');
 await expect(page.locator('.scheduling-orders-list')).toBeVisible();
});
