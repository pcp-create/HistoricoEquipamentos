-- Raw API snapshots keep source company and all fields for reconciliation/audit.
CREATE TABLE public.m8_commercial_facts (
 company_id integer NOT NULL, kind text NOT NULL CHECK(kind IN ('fContratos','fFaturamento','fDevolucoesOutros','fDevolucoesCompra')),
 id bigint NOT NULL, payload jsonb NOT NULL, present boolean NOT NULL DEFAULT true,
 collected_at timestamptz NOT NULL DEFAULT now(), PRIMARY KEY(company_id,kind,id)
);
CREATE TABLE public.m8_commercial_facts_sync (
 company_id integer NOT NULL, kind text NOT NULL, collected_at timestamptz NOT NULL DEFAULT now(),
 PRIMARY KEY(company_id,kind)
);
ALTER TABLE public.m8_commercial_facts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.m8_commercial_facts_sync ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public.m8_commercial_facts,public.m8_commercial_facts_sync FROM PUBLIC,anon,authenticated;
